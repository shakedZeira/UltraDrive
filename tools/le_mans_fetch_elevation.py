"""Bake real elevation data for the Le Mans No-Chicane circuit.

Writes scripts/track/le_mans_elevation_data.gd (class LeMansElevationData):
  * PROFILE_CHAINAGES / PROFILE_M  - SRTM 1-arc-second (30 m) ground elevation
    (m ASL) sampled every <= 50 m of chainage along the LeMansLayout anchor
    polyline (the same OSM trace the layout is built from);
  * GRID_*                         - a 100 m SRTM grid over the scene's ground
    plane (6 x 7 km around the layout bbox), row-major Z then X.

Source: NASA SRTM GL1 (public domain) via the OpenTopoData public API
(https://www.opentopodata.org, dataset `srtm30m`). Cross-checked against
EU-DEM v1.1 (Copernicus, dataset `eudem25m`) along the lap; the max
difference is printed and recorded in the generated file header.

Projection: the layout's local frame is X east / Z south in metres around
lat 47.9437, lon 0.21596 (docs/plans/track_le_mans_no_chicane.md §3.1 step 5),
inverted here with the same equirectangular approximation.

Run (network required, ~45 API calls, OpenTopoData allows 1 call/s and
1000/day):  py tools/le_mans_fetch_elevation.py
The output is deterministic for a given dataset version and is committed, so
the game never touches the network.
"""
import io
import json
import math
import re
import time
import urllib.request

ROOT = r'D:/AI Projects/UltraDrive'
LAYOUT = ROOT + '/scripts/track/le_mans_layout.gd'
OUT = ROOT + '/scripts/track/le_mans_elevation_data.gd'
API = 'https://api.opentopodata.org/v1/%s?locations=%s'
LAT0, LON0 = 47.9437, 0.21596
PROFILE_STEP_M = 50.0
GRID_STEP_M = 100.0
# Ground plane in le_mans.gd: GROUND_SIZE 6000 x 7000 centred on the layout
# bbox centre. Pad one cell so bilinear lookups never fall off the grid.
PLANE_HALF = (3000.0 + GRID_STEP_M, 3500.0 + GRID_STEP_M)


def to_latlon(x, z):
    lat = LAT0 - z / 111320.0
    lon = LON0 + x / (111320.0 * math.cos(math.radians(LAT0)))
    return lat, lon


def query(dataset, latlons):
    out = []
    for b in range(0, len(latlons), 100):
        chunk = latlons[b:b + 100]
        locs = '|'.join('%.6f,%.6f' % p for p in chunk)
        data = json.load(urllib.request.urlopen(API % (dataset, locs), timeout=60))
        if data.get('status') != 'OK':
            raise RuntimeError(data)
        out += [float(r['elevation']) for r in data['results']]
        time.sleep(1.2)
    return out


def main():
    src = io.open(LAYOUT, encoding='utf-8').read()
    a_txt = src[src.index('const ANCHORS'):src.index('const ANCHOR_CHAINAGES')]
    anchors = [(float(x), float(z)) for x, z in re.findall(r'Vector2\(([-\d.]+),\s*([-\d.]+)\)', a_txt)]
    c_txt = src[src.index('const ANCHOR_CHAINAGES'):src.index('## Bermed corners')]
    chs = [float(v) for v in re.findall(r'([\d.]+),', c_txt.split('[', 1)[1])]
    assert len(anchors) == len(chs) == 51
    anchors.append(anchors[0])
    chs.append(13626.0)

    prof_ch, prof_ll = [], []
    for i in range(51):
        (x0, z0), (x1, z1) = anchors[i], anchors[i + 1]
        c0, c1 = chs[i], chs[i + 1]
        n = max(1, int(math.ceil((c1 - c0) / PROFILE_STEP_M)))
        for k in range(n):
            t = k / n
            prof_ch.append(c0 + (c1 - c0) * t)
            prof_ll.append(to_latlon(x0 + (x1 - x0) * t, z0 + (z1 - z0) * t))
    srtm = query('srtm30m', prof_ll)
    eudem = query('eudem25m', prof_ll)
    max_diff = max(abs(a - b) for a, b in zip(srtm, eudem))

    xs = [a[0] for a in anchors]
    zs = [a[1] for a in anchors]
    cx, cz = (min(xs) + max(xs)) * 0.5, (min(zs) + max(zs)) * 0.5
    x0, z0 = cx - PLANE_HALF[0], cz - PLANE_HALF[1]
    nx = int(round(PLANE_HALF[0] * 2 / GRID_STEP_M)) + 1
    nz = int(round(PLANE_HALF[1] * 2 / GRID_STEP_M)) + 1
    grid_ll = [to_latlon(x0 + i * GRID_STEP_M, z0 + j * GRID_STEP_M) for j in range(nz) for i in range(nx)]
    grid = query('srtm30m', grid_ll)

    def fmt(vals, per=12):
        rows = []
        for b in range(0, len(vals), per):
            rows.append('\t' + ', '.join('%.1f' % v for v in vals[b:b + per]) + ',')
        return '\n'.join(rows)

    with io.open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('class_name LeMansElevationData\nextends RefCounted\n\n')
        f.write('## GENERATED by tools/le_mans_fetch_elevation.py - do not hand-edit.\n')
        f.write('## Real ground elevation (m above sea level) for the Le Mans No-Chicane\n')
        f.write('## circuit: NASA SRTM GL1 30 m (public domain) via OpenTopoData\n')
        f.write('## (dataset srtm30m). Lap profile cross-checked against EU-DEM v1.1\n')
        f.write('## (Copernicus, eudem25m): max |SRTM - EU-DEM| along the lap = %.1f m.\n' % max_diff)
        f.write('## SRTM is a surface model (C-band partly reflects canopy/buildings) and\n')
        f.write('## the OSM trace is +-10-30 m laterally, so LeMansLayout SMOOTHS this.\n\n')
        f.write('## Lap profile: chainage (m from the S/F line, OSM anchor frame) -> m ASL.\n')
        f.write('const PROFILE_CHAINAGES: Array[float] = [\n%s\n]\n' % fmt(prof_ch, 10))
        f.write('const PROFILE_M: Array[float] = [\n%s\n]\n\n' % fmt(srtm))
        f.write('## Surrounding-terrain grid (layout frame: X east, Z south, metres).\n')
        f.write('const GRID_ORIGIN := Vector2(%.1f, %.1f)\n' % (x0, z0))
        f.write('const GRID_STEP_M := %.1f\n' % GRID_STEP_M)
        f.write('const GRID_NX := %d\nconst GRID_NZ := %d\n' % (nx, nz))
        f.write('## Row-major: index = iz * GRID_NX + ix.\n')
        f.write('const GRID_M: Array[float] = [\n%s\n]\n' % fmt(grid))
    print('profile', len(prof_ch), 'min %.1f max %.1f' % (min(srtm), max(srtm)),
          'eudem max diff %.1f' % max_diff, 'grid %dx%d' % (nx, nz),
          'grid min %.1f max %.1f' % (min(grid), max(grid)))


if __name__ == '__main__':
    main()
